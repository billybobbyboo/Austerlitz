/* WP-15's triage (docs/ROADMAP_FINAL_AUDIT.md, WP-15; finding CL-SRC-10, ChatGPT CG-F02): every unchecked narrative statement ranked by
   prominence. Reads docs/step4-evidence/inventory.json (every statement by ref, class and claim; kept current by test.js), the sources
   (tools/wp15/tiers.js: app.js's opening, data.js's formations and tour) and, where it exists, docs/wp15-evidence/proposals.json (to mark
   the first batch); writes docs/wp15-evidence/triage.json and triage.md. Deterministic: the same files give the same output.
     node tools/wp15/triage.js           write the two files
     node tools/wp15/triage.js --check   exit 1 if either file differs from what the sources give now */
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "..", ".."), OUT = path.join(ROOT, "docs", "wp15-evidence");
const T = require("./tiers.js");

function build() {
  const inv = JSON.parse(fs.readFileSync(path.join(ROOT, "docs", "step4-evidence", "inventory.json"), "utf8"));
  const C = T.sourceContext(ROOT), ranked = T.rank(inv.rows, C);
  const pf = path.join(OUT, "proposals.json"), P = fs.existsSync(pf) ? JSON.parse(fs.readFileSync(pf, "utf8")) : { proposals: [] };
  const mark = new Map(P.proposals.map(p => [p.ref, p.extra ? (p.claim ? "found: claim" : "found: correction") : (p.claim ? "batch 1: claim" : "batch 1: correction")]));
  /* the projection: a statement with a proposed claim as it stands is no longer unchecked (A); with the corrections too (B). The verifier,
     tools/wp15/apply-proposals.js, confirms it by running test.js on a copy */
  const projA = new Set(P.proposals.filter(p => p.claim).map(p => p.ref));
  const projB = new Set(P.proposals.filter(p => p.claim || (p.correction && p.correction.appliedForTest)).map(p => p.ref));
  const after = set => T.counts(ranked.map(r => set.has(r.ref) ? Object.assign({}, r, { claim: "proposed" }) : r));
  const counts = { before: T.counts(ranked), afterClaims: after(projA), afterCorrections: after(projB) };
  const groups = Object.keys(T.GROUPS).map(g => {
    const rs = ranked.filter(r => r.group === g);
    return { group: g, tier: rs.length ? rs[0].tier : +g[0], what: T.GROUPS[g], statements: rs.length, unchecked: rs.filter(T.isUnchecked).length,
      inBatch: rs.filter(r => (mark.get(r.ref) || "").startsWith("batch")).length };
  });
  const rows = ranked.filter(T.isUnchecked).map(r => ({ rank: r.rank, tier: r.tier, group: r.group, ref: r.ref, cls: r.cls, file: r.file, line: r.line,
    text: (r.label ? r.label + " / " : "") + r.text, batch: mark.get(r.ref) || null }));
  return { source: "docs/step4-evidence/inventory.json", opening: C.stops, groups, counts, unchecked: rows };
}

function md(J) {
  const L = [], q = t => String(t).replace(/\|/g, "\\|").replace(/\s+/g, " "), cut = t => { t = q(t); return t.length > 110 ? t.slice(0, 109) + "…" : t; };
  const tiers = ["tier 1", "tier 2", "tier 3"], c = J.counts;
  L.push("# WP-15's triage: the unchecked narrative statements, ranked by prominence", "",
    "Generated by `node tools/wp15/triage.js` (with `triage.json`) from `docs/step4-evidence/inventory.json` and the sources; never edited by",
    "hand. The final audits' Stage 4, alongside track (`docs/ROADMAP_FINAL_AUDIT.md`, WP-15; finding CL-SRC-10, ChatGPT's CG-F02).", "",
    "## The tiers, and why", "",
    "A statement's tier is where a visitor meets it, first by what the page shows without being asked, then by what one press shows.",
    "Every statement of the inventory gets one tier and one group (`tools/wp15/tiers.js`); the rank orders them all.", "",
    "- **Tier 1, what a visitor reads first or reads in every phase.**",
    "  - *1a, the first screen*: phase 0's lede. The page opens at 04:00 (`app.js` `T_MIN`), where the Now tab's dispatch shows phase 0's",
    "    lede beside the first-run card from 1080 px wide (decision 113), and the dispatch card below that width.",
    "  - *1b, the opening*: the tour stops `app.js`'s `OPENING.stops` plays (" + J.opening.map(k => "TOUR[" + k + "]").join(", ") + "), in its order: the first",
    "    screen's primary action begins it.",
    "  - *1c, the rest of the tour*, in its order.",
    "  - *1d, the phase ledes of phases 1-9*: the Now tab and the dispatch card show each while the clock is in its phase.",
    "  - *1e, the headline strengths*: each army's total and its source line, then each corps-level formation's strength note (the army",
    "    card and the dossiers; echelon \"corps\" in `FORMATIONS`).",
    "  - *1f, the Command tab's rows*, by phase, French before Allied: one press away, read as what each command saw, knew and ordered.",
    "- **Tier 2, what the timeline and the panels show beside them**: the phase lines and the phase flash, the events' names, whys and",
    "  disputes (the timeline's markers and the caption), the themes, the places' subtitles, the plans and their orders, the acts.",
    "- **Tier 3, the rest**: the formations' other fields (the division-level strength notes among them), the tracks' acts and objectives, the",
    "  timing notes, the places' stories, facts and reasons, and the sources sheet's method statements.", "",
    "**Within a tier** the groups come in the order above; inside a group, in the order a visitor meets them (the opening's order, the",
    "tour's, the phases', `FORMATIONS`' order, the Command tab's), else in source order; tier 3 by class (formation, track act, track",
    "objective, timing note, place, place fact, place why, method), then in source order. The rank counts every statement, claimed or not",
    "(the queue below has gaps where a statement already carries a claim), so a statement's rank stays the same as later batches claim more.", "",
    "## The counts", "",
    "Unchecked statements, before this batch and as `proposals.json` projects them: with its claims on the statements as they stand (A),",
    "and with its corrections applied too (B). `node tools/wp15/apply-proposals.js` confirms both by running `test.js` on a copy",
    "(`apply-proposals.log`).", "",
    "| tier | statements | unchecked before | after A (claims) | after B (and corrections) |", "|---|---|---|---|---|");
  tiers.forEach(t => L.push("| " + t + " | " + c.before.statements[t] + " | " + (c.before.unchecked[t] || 0) + " | " + (c.afterClaims.unchecked[t] || 0) + " | " + (c.afterCorrections.unchecked[t] || 0) + " |"));
  const sum = k => tiers.reduce((a, t) => a + (c[k].unchecked[t] || 0), 0);
  L.push("| all | " + tiers.reduce((a, t) => a + c.before.statements[t], 0) + " | " + sum("before") + " | " + sum("afterClaims") + " | " + sum("afterCorrections") + " |", "",
    "| tier | class | unchecked before | after A | after B |", "|---|---|---|---|---|");
  tiers.forEach(t => Object.keys(c.before.uncheckedByClass[t] || {}).sort().forEach(k =>
    L.push("| " + t + " | " + k + " | " + c.before.uncheckedByClass[t][k] + " | " + ((c.afterClaims.uncheckedByClass[t] || {})[k] || 0) + " | " + ((c.afterCorrections.uncheckedByClass[t] || {})[k] || 0) + " |")));
  L.push("", "## The groups", "", "| group | tier | what | statements | unchecked | in batch 1 |", "|---|---|---|---|---|---|");
  J.groups.forEach(g => L.push("| " + g.group + " | " + g.tier + " | " + g.what + " | " + g.statements + " | " + g.unchecked + " | " + g.inBatch + " |"));
  L.push("", "## The queue: every unchecked statement, by rank", "",
    "*batch 1*: in WP-15's first batch (`proposals.md`), with a claim proposed for the statement as it stands, or a correction; *found*: proposed",
    "beside the batch.", "", "| rank | group | statement | class | where | text | batch |", "|---|---|---|---|---|---|---|");
  J.unchecked.forEach(r => L.push("| " + r.rank + " | " + r.group + " | `" + q(r.ref) + "` | " + r.cls + " | " + r.file + ":" + r.line + " | " + cut(r.text) + " | " + (r.batch || "") + " |"));
  L.push("");
  return L.join("\n");
}

if (require.main === module) {
  const J = build(), outJ = JSON.stringify(J, null, 1) + "\n", outM = md(J) + "\n";
  const fj = path.join(OUT, "triage.json"), fm = path.join(OUT, "triage.md");
  if (process.argv.includes("--check")) {
    const bad = [[fj, outJ], [fm, outM]].filter(([f, t]) => !fs.existsSync(f) || fs.readFileSync(f, "utf8") !== t).map(([f]) => path.relative(ROOT, f));
    console.log(bad.length ? "OUT OF DATE: " + bad.join(", ") : "triage current");
    process.exit(bad.length ? 1 : 0);
  }
  fs.mkdirSync(OUT, { recursive: true }); fs.writeFileSync(fj, outJ); fs.writeFileSync(fm, outM);
  const b = J.counts.before.unchecked;
  console.log("wrote " + path.relative(ROOT, fj) + " and " + path.relative(ROOT, fm) + ": " + J.unchecked.length + " unchecked statements ranked (tier 1 " +
    (b["tier 1"] || 0) + ", tier 2 " + (b["tier 2"] || 0) + ", tier 3 " + (b["tier 3"] || 0) + ")");
}
module.exports = { build };
