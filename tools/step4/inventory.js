/* Roadmap step 4 (docs/FINAL_AUDIT.md H-6; owner decisions 128 (b), 130): the inventory of the narrative statements and their claims.
   Writes docs/step4-evidence/inventory.json and inventory.md from tools/step4/statements.js (every narrative statement of data.js and
   analysis.js, by ref) and, where it exists, narrative.js's STATEMENT_CLAIMS (a statement without an entry is "unchecked": not yet
   checked against a source read here). Read-only but for the two files; loads no page.
     node tools/step4/inventory.js           write the two files
     node tools/step4/inventory.js --check   exit 1 if either file differs from what the sources give now */
"use strict";
const fs=require("fs"), path=require("path"), vm=require("vm");
const ROOT=path.resolve(__dirname,"..",".."), OUTDIR=path.join(ROOT,"docs","step4-evidence");
const {statements}=require("./statements.js");

function claimsTable(root){
  const f=path.join(root,"narrative.js"); if(!fs.existsSync(f)) return {claims:{}};
  const ctx={}; vm.runInNewContext(fs.readFileSync(f,"utf8")+"\n;this.__c=STATEMENT_CLAIMS;this.__k=typeof CLAIM_BY_CLASS!=='undefined'?CLAIM_BY_CLASS:{};",ctx);
  return {claims:ctx.__c||{},byClass:ctx.__k||{}};
}
function inventory(root){
  const S=statements(root), {claims,byClass}=claimsTable(root);
  /* decision 187 (iii): a framing statement without its own entry takes its class's claim (CLAIM_BY_CLASS) */
  const classClaim=s=>Object.prototype.hasOwnProperty.call(byClass,s.cls)&&byClass[s.cls]&&typeof byClass[s.cls].cl==="string"?byClass[s.cls].cl:null;
  /* a malformed entry is test.js's to report; here it never throws (the review of f40ea90) */
  const rows=S.map(s=>{ const c=Object.prototype.hasOwnProperty.call(claims,s.ref)&&claims[s.ref]&&typeof claims[s.ref]==="object"?claims[s.ref]:null;
    return {ref:s.ref,cls:s.cls,file:s.file,line:s.line,label:s.label,text:s.text,
      claim:c?String(c.cl):(classClaim(s)?classClaim(s)+" (by class)":"unchecked"),by:c&&Array.isArray(c.by)?c.by.filter(b=>b&&typeof b==="object").map(b=>({src:b.src,at:b.at,rd:b.rd,side:b.side})):[]}; });
  const count=(k)=>rows.reduce((a,r)=>(a[r[k]]=(a[r[k]]||0)+1,a),{});
  return {statements:rows.length,byClass:count("cls"),byClaim:count("claim"),rows};
}
function markdown(inv){
  const esc=t=>String(t).replace(/\|/g,"\\|").replace(/\s+/g," ");
  const cut=t=>{ t=esc(t); return t.length>140?t.slice(0,139)+"…":t; };
  const L=["# The narrative statements and their claims (roadmap step 4)","",
    "Generated by `node tools/step4/inventory.js` from `tools/step4/statements.js` and `narrative.js`'s `STATEMENT_CLAIMS`; never edited by hand",
    "(`node tools/step4/inventory.js --check` fails when this file or `inventory.json` differs from what the sources give). One statement per string a visitor reads as a",
    "statement about the battle or about this map's method (the class table in `tools/step4/statements.js` says which paths, and what is",
    "excluded and why). A statement with no entry in `STATEMENT_CLAIMS` takes its class's claim where `CLAIM_BY_CLASS` names its class",
    "(\"by class\": the framing statements, decision 187 (iii)), and is otherwise **unchecked**: not yet checked against a source read here",
    "(its own citation, where it names one, is not checked here either). The readings named are in `docs/step4-evidence/readings.md` (C*n*.*k*)",
    "or `docs/step2-evidence/readings.md` (§*n*.*k*).","",
    "**"+inv.statements+" statements.**","",
    "| class | statements |","|---|---|"].concat(Object.entries(inv.byClass).map(([k,v])=>"| "+k+" | "+v+" |"),["",
    "| claim | statements |","|---|---|"],Object.entries(inv.byClaim).sort((a,b)=>b[1]-a[1]).map(([k,v])=>"| "+k+" | "+v+" |"),[""]);
  const classes=[...new Set(inv.rows.map(r=>r.cls))];
  classes.forEach(c=>{ L.push("## "+c,"","| ref | where | statement | claim | readings |","|---|---|---|---|---|");
    inv.rows.filter(r=>r.cls===c).forEach(r=>L.push("| `"+r.ref+"` | "+r.file+":"+r.line+" | "+cut((r.label?r.label+" / ":"")+r.text)+" | "+r.claim+" | "+
      (r.by.length?r.by.map(b=>esc((b.rd||b.src)+(b.side?" ("+b.side+")":""))).join("; "):"")+" |"));
    L.push(""); });
  return L.join("\n");
}
module.exports={inventory,markdown,claimsTable};
if(require.main===module){
  const inv=inventory(ROOT), json=JSON.stringify(inv,null,1)+"\n", md=markdown(inv)+"\n";
  const fj=path.join(OUTDIR,"inventory.json"), fm=path.join(OUTDIR,"inventory.md");
  if(process.argv.includes("--check")){
    const bad=[[fj,json],[fm,md]].filter(([f,t])=>!fs.existsSync(f)||fs.readFileSync(f,"utf8")!==t).map(([f])=>path.relative(ROOT,f));
    console.log("inventory: "+inv.statements+" statements; "+Object.entries(inv.byClaim).map(([k,v])=>k+" "+v).join(", ")+
      (bad.length?"; OUT OF DATE: "+bad.join(", ")+" (run node tools/step4/inventory.js)":"; the committed inventory is current"));
    process.exit(bad.length?1:0);
  }
  fs.mkdirSync(OUTDIR,{recursive:true}); fs.writeFileSync(fj,json); fs.writeFileSync(fm,md);
  console.log("wrote "+path.relative(ROOT,fj)+" and "+path.relative(ROOT,fm)+": "+inv.statements+" statements");
}
