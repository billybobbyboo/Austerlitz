#!/usr/bin/env node
/* Roadmap step 6 Part A (docs/STEP6_SPEC.md section 3.1): docs/step6-evidence/census.json (tools/step6/census.js) as tables.
   node tools/step6/census-report.js docs/step6-evidence/census.json > docs/step6-evidence/census.md
   Reads the JSON only; arithmetic, no measurement. */
const fs=require("fs");
const R=JSON.parse(fs.readFileSync(process.argv[2],"utf8")), V=R.views, out=[];
const k=n=>n==null?"-":n>=1e6?(n/1e6).toFixed(2)+" M":n>=1e3?(n/1e3).toFixed(1)+" k":String(n);
const pc=(a,b)=>b?(100*a/b).toFixed(1)+"%":"-";
out.push("# The census of one whole frame (tools/step6/census.js)\n");
out.push("Generated by `node tools/step6/census-report.js docs/step6-evidence/census.json` from the census run on the unchanged build. "+
  "Software WebGL; the counts are what the build asks the GPU to draw at 1600 x 900 (1280 x 720 and 1024 x 768 where the case says), the same on any GPU. "+
  "Triangles count every pass: the world, the shadow map (drawn from the sun) and post-processing. `figures` is every mesh of a formation's block "+
  "(men, horses, guns and gear, standards).\n");
out.push("## By view\n");
out.push("| view | calls | triangles | world | shadow | post | figures, all passes | figures' share | figure calls | figures in the shadow pass |");
out.push("|---|---|---|---|---|---|---|---|---|---|");
for(const [n,v] of Object.entries(V)){
  const P=v.byPass, fs=Object.entries(v.byWhat).filter(([w])=>/\| (figures|standards)/.test(w)).reduce((a,[w,x])=>{ a.t+=x.tris; if(w.startsWith("shadow")) a.s+=x.tris; return a; },{t:0,s:0});
  out.push(`| ${n} | ${v.calls} | ${k(v.tris)} | ${k((P.world||{}).tris)} | ${k((P.shadow||{}).tris||0)} | ${k((P.post||{}).tris||0)} | ${k(fs.t)} | ${pc(fs.t,v.tris)} | ${v.figures.calls} | ${k(fs.s)} |`);
}
const pick=["pratzen-low","overview-field","ph8-overview-watch","close-sokolnitz","pratzen-low-1x","paper-north-up","eye-zuran"].filter(n=>V[n]);
for(const n of pick){
  const v=V[n];
  out.push(`\n## ${n}: what is drawn, by pass\n`);
  out.push("| pass | what | calls | triangles | share of the frame | instances |"); out.push("|---|---|---|---|---|---|");
  Object.entries(v.byWhat).sort((a,b)=>b[1].tris-a[1].tris).forEach(([w,x])=>{ const [p,what]=w.split(" | "); if(x.tris<1000&&x.calls<5) return;
    out.push(`| ${p} | ${what} | ${x.calls} | ${k(x.tris)} | ${pc(x.tris,v.tris)} | ${x.inst} |`); });
  if(Object.keys(v.figBands).length){
    out.push(`\nThe figures by their block's distance from the eye (world units; ${(63.2).toFixed(1)} m each, GEOREF.M_PER_WORLD):\n`);
    out.push("| pass | distance | calls | triangles |"); out.push("|---|---|---|---|");
    Object.entries(v.figBands).sort().forEach(([b,x])=>out.push(`| ${b.split(" | ")[0]} | ${b.split(" | ")[1]} | ${x.calls} | ${k(x.tris)} |`));
    out.push("\nThe figures in the world pass by a man's height on screen (CSS px, at the block's first instance):\n");
    out.push("| a man's height | calls | triangles | instances |"); out.push("|---|---|---|---|");
    const ord=["<2 px","<4 px","<8 px","<16 px","<inf px"];
    ord.filter(b=>v.figPx[b]).forEach(b=>{ const x=v.figPx[b]; out.push(`| ${b.replace("<inf","16 px or more").replace("<2 px","under 2 px").replace("<4 px","2-4 px").replace("<8 px","4-8 px").replace("<16 px","8-16 px")} | ${x.calls} | ${k(x.tris)} | ${x.inst} |`); });
    out.push(`\nDistinct figure geometries and textures drawn: ${v.figures.distinctGeoWorld} in the world pass, ${v.figures.distinctGeoAllPasses} counting each pass (what instancing across blocks would draw as one call each); the figures' calls now: ${v.figures.calls}.`);
  }
}
process.stdout.write(out.join("\n")+"\n");
